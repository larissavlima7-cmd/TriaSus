-- =====================================================================
-- TriaSUS Americana | schema PostgreSQL + seed de desenvolvimento
-- Uso:
--   createdb -U postgres triasus_americana
--   psql -U postgres -d triasus_americana -f database/dump_triasus.sql
-- Observações:
--   * Enums são VARCHAR + CHECK (mapear no Java com @Enumerated(EnumType.STRING)).
--   * PKs com IDENTITY (usar GenerationType.IDENTITY).
--   * Os dados do seed são FICTÍCIOS, só para desenvolvimento. Não usar em produção.
-- =====================================================================

BEGIN;

DROP TABLE IF EXISTS log_auditoria        CASCADE;
DROP TABLE IF EXISTS sinal_vital          CASCADE;
DROP TABLE IF EXISTS documento_anexo      CASCADE;
DROP TABLE IF EXISTS solicitacao          CASCADE;
DROP TABLE IF EXISTS checklist_protocolo  CASCADE;
DROP TABLE IF EXISTS profissional_unidade CASCADE;
DROP TABLE IF EXISTS profissional         CASCADE;
DROP TABLE IF EXISTS paciente             CASCADE;
DROP TABLE IF EXISTS especialidade        CASCADE;
DROP TABLE IF EXISTS unidade_ubs          CASCADE;
DROP TABLE IF EXISTS usuario_papel        CASCADE;
DROP TABLE IF EXISTS papel                CASCADE;
DROP TABLE IF EXISTS usuario              CASCADE;

-- ---------------------------------------------------------------------
-- Acesso e perfis (RF01, RNF02)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(150) NOT NULL,
    email       VARCHAR(150) UNIQUE,
    cpf         VARCHAR(11)  NOT NULL UNIQUE,          -- somente dígitos
    senha_hash  VARCHAR(100),                          -- nulo para cidadão (login por CPF/CNS + nascimento)
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_cpf CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE papel (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(30)  NOT NULL UNIQUE,
    descricao  VARCHAR(200),
    CONSTRAINT ck_papel_nome CHECK (nome IN ('CIDADAO', 'RECEPCAO_ACS', 'PROFISSIONAL_SAUDE'))
);

CREATE TABLE usuario_papel (
    usuario_id INT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    papel_id   INT NOT NULL REFERENCES papel(id),
    PRIMARY KEY (usuario_id, papel_id)
);

-- ---------------------------------------------------------------------
-- Cadastros base
-- ---------------------------------------------------------------------
CREATE TABLE unidade_ubs (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(150) NOT NULL,
    cnes      VARCHAR(7),
    endereco  VARCHAR(255),
    ativo     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE especialidade (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL UNIQUE,
    descricao  TEXT,
    ativo      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE paciente (
    id                    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            INT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    unidade_referencia_id INT REFERENCES unidade_ubs(id),
    cartao_sus            VARCHAR(15) UNIQUE,          -- CNS (15 dígitos)
    data_nascimento       DATE NOT NULL,
    telefone              VARCHAR(20),
    contato_validado      BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_paciente_cns CHECK (cartao_sus IS NULL OR cartao_sus ~ '^[0-9]{15}$')
);

CREATE TABLE profissional (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       INT NOT NULL UNIQUE REFERENCES usuario(id) ON DELETE CASCADE,
    funcao           VARCHAR(80) NOT NULL,             -- ex.: Enfermeiro(a), Médico(a), Recepcionista, ACS
    numero_registro  VARCHAR(30)                       -- COREN/CRM, quando aplicável
);

CREATE TABLE profissional_unidade (
    profissional_id INT NOT NULL REFERENCES profissional(id) ON DELETE CASCADE,
    unidade_id      INT NOT NULL REFERENCES unidade_ubs(id),
    PRIMARY KEY (profissional_id, unidade_id)
);

CREATE TABLE checklist_protocolo (
    id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    especialidade_id     INT NOT NULL REFERENCES especialidade(id) ON DELETE CASCADE,
    nome_documento       VARCHAR(150) NOT NULL,
    descricao_orientacao VARCHAR(255),
    obrigatorio          BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- Solicitação e anexos (RF02, RF03, RF05, RF06, RF08)
-- ---------------------------------------------------------------------
CREATE TABLE solicitacao (
    id                          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo                   VARCHAR(30) NOT NULL UNIQUE,   -- gerado pela aplicação
    paciente_id                 INT NOT NULL REFERENCES paciente(id),
    especialidade_id            INT NOT NULL REFERENCES especialidade(id),
    unidade_id                  INT NOT NULL REFERENCES unidade_ubs(id),
    profissional_conferencia_id INT REFERENCES profissional(id),  -- nulo até a conferência
    criada_por_usuario_id       INT REFERENCES usuario(id),       -- cidadão ou recepção/ACS (RF07)
    data_solicitacao            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status                      VARCHAR(30) NOT NULL DEFAULT 'RASCUNHO',
    prioridade_oficial          VARCHAR(20) NOT NULL DEFAULT 'NAO_DEFINIDA',
    queixa_relatada             TEXT,
    tempo_evolucao              VARCHAR(50),
    observacao_profissional     TEXT,
    CONSTRAINT ck_solicitacao_status CHECK (status IN
        ('RASCUNHO', 'EM_CONFERENCIA_UBS', 'PENDENCIA_DOCUMENTAL', 'APTO_REGULACAO')),
    CONSTRAINT ck_solicitacao_prioridade CHECK (prioridade_oficial IN
        ('NAO_DEFINIDA', 'BAIXA', 'MEDIA', 'ALTA', 'URGENTE')),
    -- só libera para regulação com prioridade definida por profissional
    CONSTRAINT ck_solicitacao_apto CHECK (
        status <> 'APTO_REGULACAO'
        OR (prioridade_oficial <> 'NAO_DEFINIDA' AND profissional_conferencia_id IS NOT NULL))
);

CREATE TABLE documento_anexo (
    id                    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id        INT NOT NULL REFERENCES solicitacao(id) ON DELETE CASCADE,
    item_checklist_id     INT NOT NULL REFERENCES checklist_protocolo(id),
    nome_arquivo_original VARCHAR(255),
    url_arquivo           VARCHAR(500) NOT NULL,       -- caminho interno; download só por endpoint autenticado
    tipo_mime             VARCHAR(100),
    tamanho_bytes         BIGINT,
    status_validacao      VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    motivo_rejeicao       TEXT,
    enviado_em            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_anexo_status CHECK (status_validacao IN ('PENDENTE', 'VALIDO', 'REJEITADO')),
    CONSTRAINT ck_anexo_mime   CHECK (tipo_mime IS NULL OR tipo_mime IN
        ('image/jpeg', 'image/png', 'application/pdf')),
    CONSTRAINT ck_anexo_tamanho CHECK (tamanho_bytes IS NULL OR tamanho_bytes <= 5242880),  -- 5 MB (RNF04)
    CONSTRAINT ck_anexo_motivo  CHECK (status_validacao <> 'REJEITADO' OR motivo_rejeicao IS NOT NULL)
);

-- ---------------------------------------------------------------------
-- Sinais vitais (RF04)
-- ---------------------------------------------------------------------
CREATE TABLE sinal_vital (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id      INT NOT NULL REFERENCES solicitacao(id) ON DELETE CASCADE,
    profissional_id     INT REFERENCES profissional(id),   -- nulo em auto-relato
    pressao_arterial    VARCHAR(10),                       -- ex.: 140x90
    frequencia_cardiaca INT,
    temperatura         NUMERIC(4,1),
    glicemia            INT,
    saturacao           INT,
    origem_afericao     VARCHAR(30) NOT NULL,
    aferido_em          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sinal_origem CHECK (origem_afericao IN ('ACOLHIMENTO_UBS', 'AUTO_RELATO_DOMICILIAR')),
    -- aferição oficial exige o profissional que mediu
    CONSTRAINT ck_sinal_profissional CHECK (
        origem_afericao = 'AUTO_RELATO_DOMICILIAR' OR profissional_id IS NOT NULL),
    CONSTRAINT ck_sinal_saturacao CHECK (saturacao IS NULL OR saturacao BETWEEN 0 AND 100),
    CONSTRAINT ck_sinal_pa CHECK (pressao_arterial IS NULL OR pressao_arterial ~ '^[0-9]{2,3}x[0-9]{2,3}$')
);

-- ---------------------------------------------------------------------
-- Auditoria (RNF01)
-- ---------------------------------------------------------------------
CREATE TABLE log_auditoria (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        INT REFERENCES usuario(id),          -- nulo em tentativas sem autenticação
    acao              VARCHAR(50) NOT NULL,                -- ex.: VISUALIZAR, APROVAR, DEVOLVER, ACESSO_NEGADO
    entidade_afetada  VARCHAR(50),
    registro_id       INT,
    detalhes          TEXT,
    ip_origem         VARCHAR(45),
    data_hora         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Índices (fila da UBS, checklist, auditoria)
-- ---------------------------------------------------------------------
CREATE INDEX idx_solicitacao_fila     ON solicitacao (unidade_id, status, especialidade_id, prioridade_oficial);
CREATE INDEX idx_solicitacao_paciente ON solicitacao (paciente_id);
CREATE INDEX idx_anexo_solicitacao    ON documento_anexo (solicitacao_id);
CREATE INDEX idx_sinal_solicitacao    ON sinal_vital (solicitacao_id);
CREATE INDEX idx_checklist_espec      ON checklist_protocolo (especialidade_id);
CREATE INDEX idx_log_usuario_data     ON log_auditoria (usuario_id, data_hora);
CREATE INDEX idx_log_entidade         ON log_auditoria (entidade_afetada, registro_id);

